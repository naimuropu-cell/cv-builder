function bindField(elementId, stateKey) {
  const el = document.getElementById(elementId);
  if (!el) return;
  el.value = cvState[stateKey] || '';
  el.oninput = (e) => {
    cvState[stateKey] = e.target.value;
    renderPreview();
    calculateAtsScore();
  };
}

