function renderSkillsRepeater() {
  const container = document.getElementById('skills-repeater-list');
  if (!container) return;
  container.innerHTML = '';

  (cvState.skills || []).forEach((item, idx) => {
    const card = document.createElement('div');
    card.className = 'item-repeater';
    card.innerHTML = `
      <div class="repeater-header">
        <span class="repeater-title">Skill Group #${idx + 1}: ${item.category || 'Category'}</span>
        <button class="btn-remove" data-idx="${idx}">✕ Delete</button>
      </div>
      <div class="form-group">
        <label class="form-label">Category Name</label>
        <input type="text" class="form-input skill-cat" value="${item.category || ''}" placeholder="e.g. QA Methodologies">
      </div>
      <div class="form-group">
        <label class="form-label">Skills List (Comma separated)</label>
        <textarea class="form-textarea skill-items" placeholder="Manual Testing, Playwright, Jira...">${item.items || ''}</textarea>
      </div>
    `;

    card.querySelector('.btn-remove').onclick = () => {
      cvState.skills.splice(idx, 1);
      renderSkillsRepeater();
      renderPreview();
      calculateAtsScore();
    };

    card.querySelector('.skill-cat').oninput = (e) => {
      item.category = e.target.value;
      card.querySelector('.repeater-title').textContent = `Skill Group #${idx + 1}: ${item.category || 'Category'}`;
      renderPreview();
    };

    card.querySelector('.skill-items').oninput = (e) => {
      item.items = e.target.value;
      renderPreview();
      calculateAtsScore();
    };

    container.appendChild(card);
  });
}

