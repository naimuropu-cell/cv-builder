// ATS Score Gauge & Calculation
// ============================================================
function calculateAtsScore() {
  let score = 0;
  const checks = [];

  // 1. Basic Info Check (25 pts)
  if (cvState.name && cvState.title) { score += 10; checks.push({ pass: true, text: "Candidate Name & Target Title defined" }); }
  else { checks.push({ pass: false, text: "Missing Name or Target Title" }); }

  if (cvState.email && cvState.phone && cvState.location) { score += 15; checks.push({ pass: true, text: "Complete Contact Information" }); }
  else { checks.push({ pass: false, text: "Add complete contact details (email, phone, location)" }); }

  // 2. Summary Check (15 pts)
  if (cvState.summary && cvState.summary.length > 100) { score += 15; checks.push({ pass: true, text: "Strong Professional Summary (>100 chars)" }); }
  else { checks.push({ pass: false, text: "Summary too short or missing" }); }

  // 3. Experience & Bullet Points (30 pts)
  if (cvState.experience && cvState.experience.length >= 2) { score += 15; checks.push({ pass: true, text: "Multiple verifiable roles listed" }); }
  else { checks.push({ pass: false, text: "Add at least 2 roles in Experience" }); }

  let totalBullets = 0;
  let hasMetrics = false;
  cvState.experience.forEach(e => {
    totalBullets += (e.bullets || []).length;
    (e.bullets || []).forEach(b => {
      if (/\d+/.test(b)) hasMetrics = true;
    });
  });

  if (totalBullets >= 4 && hasMetrics) { score += 15; checks.push({ pass: true, text: "Quantified bullet points with metrics (numbers/%/scale)" }); }
  else { checks.push({ pass: false, text: "Include numbers or measurable metrics in job bullets" }); }

  // 4. Skills & Education (20 pts)
  if (cvState.skills && cvState.skills.length >= 3) { score += 10; checks.push({ pass: true, text: "Categorized Technical Skills section" }); }
  else { checks.push({ pass: false, text: "List at least 3 categorized skills" }); }

  if (cvState.education && cvState.education.length >= 1) { score += 10; checks.push({ pass: true, text: "Education credentials specified" }); }
  else { checks.push({ pass: false, text: "Add education degree & institution" }); }

  // 5. Links & Proof of Work (10 pts)
  if (cvState.github || cvState.portfolio || cvState.linkedin) { score += 10; checks.push({ pass: true, text: "Proof-of-work links (GitHub / Portfolio / LinkedIn)" }); }
  else { checks.push({ pass: false, text: "Add GitHub or Portfolio link" }); }

  // Update UI
  const scoreNum = document.getElementById('ats-score-num');
  const checklist = document.getElementById('ats-checklist');
  if (scoreNum) scoreNum.textContent = `${score}%`;
  if (checklist) {
    checklist.innerHTML = checks.map(c => `
      <li class="${c.pass ? 'ats-pass' : 'ats-warn'}">
        ${c.pass ? '✓' : '⚠️'} ${c.text}
      </li>
    `).join('');
  }
}

